"""The Phase 1 product catalogue, as data.

This list seeds the `plans` table once (migration 077_billing_catalog) and is
what `scripts/stripe_sync_catalog.py` creates in Stripe. After seeding, the
`plans` rows are the source of truth: staff change prices in the console and
the sync script creates a new Stripe Price for the changed amount. Nothing
here is charged unless BILLING_ENABLED is on (see app/services/billing).

`grants` are the entitlements a purchase or an active subscription gives:
- bool values switch a capability on;
- int values are a quantity (credits for one-off purchases, a monthly
  allowance for subscriptions);
- `ai_allowance_multiplier` multiplies AI_FREE_MONTHLY_TOKENS.
`duration_days` bounds one-off grants: how long a placement runs (featured,
urgent, profile boost) or when unused credits expire (12 months).
"""

